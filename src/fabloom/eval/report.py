"""The benchmark report: generated from a bench directory, never written by hand.

Every number says how it was measured, and failures are listed rather than averaged away.
The same ``Gate`` list CI checks is the one printed here.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from pathlib import Path

from fabloom.eval.gates import Gate
from fabloom.eval.results import ArmSummary, BenchResults, wilson_interval

MAX_FAILED_LISTED = 5


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{100 * x:.0f}%"


def _usd(x: float | None) -> str:
    return "n/a" if x is None else f"${x:.4f}"


def _secs(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.0f}s"


def _num(x: float | None, fmt: str = ".2f") -> str:
    return "n/a" if x is None else format(x, fmt)


def _rate(passed: int, n: int) -> str:
    if n == 0:
        return "n/a"
    ci = wilson_interval(passed, n)
    assert ci is not None  # noqa: S101 - n > 0
    return f"{passed}/{n} ({_pct(passed / n)}, {_pct(ci[0])} to {_pct(ci[1])})"


def _table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(r) + " |" for r in rows]
    return out


def _search_lines(summaries: Mapping[str, ArmSummary]) -> list[str]:
    searches = {a: s.grounding_searches for a, s in summaries.items() if s.grounding_searches}
    if not searches:
        return []
    # Tavily bills in search credits, not dollars, so these are not in $/scenario.
    used = ", ".join(f"`{a}` {n}" for a, n in searches.items())
    return [f"Doc searches (Tavily credits, not included in $/scenario): {used}.", ""]


def render(results: BenchResults, gates: Sequence[Gate], source: str = "") -> str:
    meta = results.meta
    summaries = results.summaries()
    lines = [
        f"# Fabloom benchmark {meta.benchmark}",
        "",
        "<!-- Generated by `fabloom bench report`; do not edit by hand. -->",
        "",
        f"**How this was measured.** {len(meta.scenarios)} scenarios x {len(meta.arms)} arms, "
        "one run each, through the same run state machine the product uses. Each run is graded "
        "against the scenario's ground-truth intent: checks are compiled from that intent, never "
        f"from model output, and evaluated by the `{meta.verifier}` verifier. "
        f"Bench `{meta.bench_id}`, commit `{meta.git_sha}`, prompts `{meta.prompt_hash}`, "
        f"scenario set `{meta.scenarios_key}`, started {meta.created:%Y-%m-%d %H:%M} UTC"
        + (f", from `{source}`" if source else "")
        + ".",
        "",
    ]
    if not meta.prices_verified:
        lines += [
            "> **Costs are estimates.** At least one model's price in `conf/models.yaml` has not "
            "been confirmed by `spikes/nemotron_probe.py`; unconfirmed prices are set "
            "pessimistically. Token counts are as reported by Token Factory.",
            "",
        ]
    if results.incomplete:
        lines += [
            f"> **Incomplete.** {len(results.incomplete)} run(s) never finished and are left out "
            f"of every number below: {', '.join(f'`{r}`' for r in results.incomplete)}.",
            "",
        ]

    lines += ["## Results", ""]
    lines += _table(
        [
            "Arm",
            "First-pass",
            "Final pass (95% CI)",
            "Mean repair rounds",
            "Unrecognised lines",
            "Pre-lint rejects",
            "$/scenario",
            "Wall p50 / p95",
        ],
        [
            [
                f"`{arm}`",
                _pct(s.first_pass_rate),
                _rate(s.passed, s.n),
                _num(s.mean_repair_rounds),
                _pct(s.unrecognized_line_rate),
                _pct(s.prelint_reject_rate),
                _usd(s.usd_per_scenario),
                f"{_secs(s.wall_p50_s)} / {_secs(s.wall_p95_s)}",
            ]
            for arm, s in summaries.items()
        ],
    )
    total_usd = sum(s.usd_total for s in summaries.values())
    lines += ["", f"Total spend for this bench: {_usd(total_usd)}.", ""]
    lines += _search_lines(summaries)

    lines += ["## Final pass rate by family", ""]
    rows = []
    for family in results.families:
        ids = {i for i, f in meta.scenarios.items() if f == family}
        row = [f"`{family}`"]
        for arm in results.arm_names:
            s = results.summary(arm, ids)
            row.append(f"{s.passed}/{s.n}" if s.n else "n/a")
        rows.append(row)
    lines += _table(["Family", *(f"`{a}`" for a in results.arm_names)], rows)
    lines += [""]

    lines += ["## Gates", ""]
    lines += _table(
        ["Gate", "Value", "Threshold", "Result", "Detail"],
        [
            [
                g.label,
                _num(g.value, "+.3f"),
                f"{g.comparison} {g.threshold:+.3f}",
                g.status.upper(),
                g.detail,
            ]
            for g in gates
        ],
    )
    lines += [""]

    lines += [
        "## Failures",
        "",
        "Every run that did not pass, with its best candidate's failures.",
        "",
    ]
    any_failed = False
    for arm in results.arm_names:
        failed = [r for r in results.records_for(arm) if not r.passed]
        if not failed:
            continue
        any_failed = True
        lines += [f"### `{arm}`", ""]
        for r in sorted(failed, key=lambda r: r.scenario_id):
            if r.error:
                why = f"error: {r.error}"
            elif r.budget_limit:
                why = f"budget stop ({r.budget_limit}); failing: " + _checks(r.failed_checks)
            else:
                why = "failing: " + _checks(r.failed_checks)
            lines.append(
                f"- `{r.scenario_id}`: {r.outcome}, score {r.final_score:.3f} after "
                f"{r.repair_rounds} repair round(s); {why}"
            )
        lines += [""]
    if not any_failed:
        lines += ["None.", ""]

    lines += ["## Arms", ""]
    for name, am in meta.arms.items():
        models = ", ".join(f"{role} `{model}`" for role, model in sorted(am.models.items()))
        lines.append(
            f"- `{name}`: {am.description} Up to {am.max_repair_rounds} repair round(s), "
            f"{am.repair_candidates} candidate(s) per round, ${am.max_usd:.2f} run cap. "
            f"Routing: {models}."
        )
    lines += [
        "",
        "## Definitions",
        "",
        "- **First-pass**: the first generated candidate passed every compiled check, "
        "before any repair.",
        "- **Final pass**: the run ended with a candidate passing every compiled check. The "
        "interval is a 95% Wilson score interval over scenarios; with tens of scenarios it is "
        "wide, and differences inside it are not evidence.",
        "- **Unrecognised lines**: share of runs whose first candidate contained a line the "
        "parser did not recognise (the model invented a command), over runs whose first "
        "candidate reached a backend.",
        "- **Pre-lint rejects**: share of runs whose first candidate the deterministic pre-lint "
        "rejected before any backend ran.",
        "- **$/scenario**: mean model spend per run, from token counts and the prices in "
        "conf/models.yaml.",
        "- **Wall**: run start to finish, nearest-rank percentiles.",
        "",
    ]
    return "\n".join(lines)


def _checks(ids: Sequence[str]) -> str:
    if not ids:
        return "no check failed"
    shown = ", ".join(f"`{i}`" for i in ids[:MAX_FAILED_LISTED])
    more = len(ids) - MAX_FAILED_LISTED
    return shown + (f" and {more} more" if more > 0 else "")


def write_report(
    path: Path, results: BenchResults, gates: Sequence[Gate], source: str = ""
) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(results, gates, source), encoding="utf-8")
